export const UNIT_PRICE_ITEMS: UnitPriceItem[] = RAW_SECTIONS.flatMap((section) =>
  section.rows.map(([name, unit, price, note], idx) => ({
    id: `${section.category}-${idx + 1}`,
    category: section.category,
    categoryLabel: section.categoryLabel,
    name,
    unit,
    price,
    ...(note ? { note } : {}),
  }))
);

export function filterPriceItems(
  items: UnitPriceItem[],
  category: string,
  query: string
): UnitPriceItem[] {
  const normalizedQuery = query.trim().toLowerCase();
  return items.filter((item) => {
    const matchesCategory = category === 'all' || !category || item.category === category;
    if (!matchesCategory) return false;
    if (!normalizedQuery) return true;
    const haystack = `${item.name} ${item.categoryLabel} ${item.note ?? ''}`.toLowerCase();
    return haystack.includes(normalizedQuery);
  });
}
